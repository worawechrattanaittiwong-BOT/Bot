assert.match(sidebar,/ownerNavItems:[\s\S]*?brokerNavItem/,'owner retains Broker nav');
assert.match(dashboard,/<ExnessSignupCard hasMt5Account=\{Boolean\(data\.account\)\} showWhenInactive=\{isOwner\}/,'owner sees Exness transfer UI on MT5 page');
