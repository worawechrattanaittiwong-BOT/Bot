const assert=require('node:assert/strict');
const fs=require('node:fs');
const read=p=>fs.readFileSync(p,'utf8');
const sidebar=read('apps/web/components/OwnerSidebar.tsx');
const page=read('apps/web/app/broker/page.tsx');
const customer=read('apps/web/components/CustomerBrokerCenter.tsx');
const dashboard=read('apps/web/app/dashboard/page.tsx');
