import assert from "node:assert/strict";
import {readFileSync} from "node:fs";
import path from "node:path";
import {createRequire} from "node:module";
import {fileURLToPath} from "node:url";
import {Module} from "node:module";
const root=path.resolve(path.dirname(fileURLToPath(import.meta.url)),"..");
const sourceFile=path.join(root,"apps/web/lib/i18n/english-mixed-copy.ts");
const require=createRequire(sourceFile);
const ts=require("typescript");
const compiled=ts.transpileModule(readFileSync(sourceFile,"utf8"),{compilerOptions:{module:ts.ModuleKind.CommonJS,esModuleInterop:true,resolveJsonModule:true}}).outputText;
const mod=new Module(sourceFile);
mod.filename=sourceFile;
mod.paths=Module._nodeModulePaths(path.dirname(sourceFile));
mod._compile(compiled,sourceFile);
const {translateEnglishCopy}=mod.exports;
assert.equal(translateEnglishCopy("15 ระดับต่อฝั่ง"),"15 levels per side");
assert.equal(translateEnglishCopy("3.00 ต่อระดับ"),"3.00 per level");
assert.equal(translateEnglishCopy("กำลังทำงาน"),"working");
assert.equal(translateEnglishCopy("ZERO GRID"),"ZERO GRID");
assert.equal(translateEnglishCopy("0.01 Lot · BUY 5 / SELL 5"),"0.01 Lot · BUY 5 / SELL 5");
assert.equal(translateEnglishCopy("ยืนยัน"),"Confirm");
console.log("English-only mixed UI translation contract: PASS");
